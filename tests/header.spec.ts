import { test, expect } from '@playwright/test';
import sharp from 'sharp';
import { PHONE } from './pages';

/**
 * Зазор над шапкой в браузере внутри приложения (F1_P80).
 *
 * Телеграм держит страницу во всю высоту экрана, а свою полосу с адресом
 * кладёт поверх неё. Стоит пролистать вниз — полоса сжимается в «пилюлю»,
 * но место под собой не освобождает: липкая шапка прилипает к нижнему краю
 * этого места, страница едет за ним, и в просвете видно верх кадра.
 *
 * Настоящий телеграм тестом не поднять, но геометрия у случая ровно та же,
 * что у шапки, отодвинутой от края окна: она стоит не у края, а ниже, и лента
 * прокручивается за ней. Поэтому тест отодвигает шапку сам и смотрит, чем
 * закрашен освободившийся кусок, — там должен быть ровный фон страницы.
 *
 * Полос-заглушек две (см. global.css), тест не различает, какая сработала:
 * проверяется результат, а не способ.
 */

/** На сколько отступает шапка от края окна — примерно как полоса телеграма. */
const BAR = 100;

test('над липкой шапкой не видно ленты', async ({ page }) => {
  await page.setViewportSize(PHONE);
  await page.goto('/');

  // Долистать до карточек: над шапкой должно оказаться что-то заметное.
  await page.evaluate(() => window.scrollTo(0, 900));
  await page.addStyleTag({
    content: `.header, .header-cover { top: ${BAR}px !important }`,
  });
  await page.waitForTimeout(300);

  const band = await page.screenshot({
    clip: { x: 0, y: 0, width: PHONE.width, height: BAR },
  });

  // Ровная полоса — значит кадр в неё не попал: у фотографии соседние точки
  // разного цвета, у подложки одного.
  const { channels } = await sharp(band).stats();
  for (const [i, channel] of channels.entries()) {
    expect(channel.max - channel.min, `над шапкой видно ленту (канал ${i})`).toBe(0);
  }
});
