import { test, expect } from '@playwright/test';
import sharp from 'sharp';
import { PHONE } from './pages';

/**
 * Зазор над шапкой в браузере внутри приложения (F1_P80).
 *
 * Телеграм (и любой другой встроенный браузер с полупрозрачной полосой сверху)
 * держит страницу во всю высоту экрана, а свою полосу кладёт поверх неё. Липкая
 * шапка в таком браузере прилипает не к краю экрана, а к нижней границе этой
 * полосы — и страница, уезжая вверх, видна над шапкой сквозь размытие.
 *
 * Настоящий телеграм тестом не поднять, но геометрия у этого случая ровно та
 * же, что у `top` больше нуля: шапка стоит не у края окна, а ниже, и лента
 * прокручивается за ней. Поэтому тест сдвигает шапку сам и смотрит, чем закрашен
 * освободившийся кусок: он должен быть ровным фоном страницы, без кадров.
 */

/** На сколько отступает шапка от края окна — примерно как полоса телеграма. */
const BAR = 100;

test('над липкой шапкой не видно ленты', async ({ page }) => {
  await page.setViewportSize(PHONE);
  await page.goto('/');

  // Долистать до карточек: над шапкой должно оказаться что-то заметное.
  await page.evaluate(() => window.scrollTo(0, 900));
  await page.addStyleTag({ content: `.header { top: ${BAR}px !important }` });
  await page.waitForTimeout(300);

  const band = await page.screenshot({
    clip: { x: 0, y: 0, width: PHONE.width, height: BAR },
  });

  // Ровная полоса — значит кадр в неё не попал: у фотографии соседние точки
  // разного цвета, у подложки одного.
  const { channels } = await sharp(band).stats();
  for (const [i, channel] of channels.entries()) {
    expect(channel.max - channel.min, `над шапкой видно ленту (канал ${i})`).toBe(0);
  }
});
